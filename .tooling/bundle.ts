// Bundles a mod's TypeScript into the one script its layout includes.
//
//   deno task bundle [mod]    <mod>/src/main.ts -> <mod>/panorama/scripts/<mod>.js
//
// `deno task dev` and `deno task build` call bundleMod() themselves (into their staged copy,
// with DEBUG set for them), so this task is only needed for the compiler menu.
//
// Output is an IIFE: Panorama scripts are classic scripts, not ES modules, and every script
// in a layout shares one global scope. Left unminified so script errors in the console point
// at readable code, and so the `DEBUG:` setting can be flipped after bundling (Deno.bundle
// has no define option).

import { dirname, fromFileUrl, join } from "@std/path";

const root = join(dirname(fromFileUrl(import.meta.url)), "..");
const NOT_MODS = new Set(["tools", "types", "test"]);

export function entryOf(mod : string, modsRoot = root) : string {
    return join(modsRoot, mod, "src", "main.ts");
}

export function outputOf(mod : string, modsRoot = root) : string {
    return join(modsRoot, mod, "panorama", "scripts", mod + ".js");
}

function exists(path : string) : boolean {
    try {
        Deno.statSync(path);
        return true;
    } catch {
        return false;
    }
}

export function listMods(modsRoot = root) : string[] {
    return [...Deno.readDirSync(modsRoot)]
        .filter((entry) => entry.isDirectory && !entry.name.startsWith(".") && !NOT_MODS.has(entry.name))
        .filter((entry) => exists(entryOf(entry.name, modsRoot)))
        .map((entry) => entry.name)
        .sort();
}

// Sets every `DEBUG: true|false` property in the bundle. null leaves the source's value.
export function setDebug(code : string, debug : boolean | null) : string {
    return debug === null ? code : code.replace(/^(\s*DEBUG\s*:\s*)(?:true|false)\b/gm, "$1" + debug);
}

// Bundles `mod` and writes it to `output`. Throws with the bundler's messages on failure.
export async function bundleMod(mod : string, output : string, debug : boolean | null) : Promise<void> {
    const entry = entryOf(mod);
    if(!exists(entry)) {
        throw new Error(mod + " has no src/main.ts");
    }

    const result = await Deno.bundle({
        entrypoints: [entry],
        format: "iife",
        platform: "browser",
        write: false,
    });
    if(!result.success || !result.outputFiles?.length) {
        const where = (m : Deno.bundle.Message) => m.location ? m.location.file + ":" + m.location.line + ": " : "";
        throw new Error("bundling " + mod + " failed:\n" + result.errors.map((m) => "  " + where(m) + m.text).join("\n"));
    }

    const header = "// Generated by `deno task bundle` from " + mod + "/src. Edit those files, not this one.\n";
    Deno.mkdirSync(dirname(output), { recursive: true });
    Deno.writeTextFileSync(output, header + setDebug(result.outputFiles[0].text(), debug));
}

if(import.meta.main) {
    const mods = listMods();
    const wanted = Deno.args.filter((arg) => !arg.startsWith("--"));
    const targets = wanted.length ? wanted : mods;
    for(const mod of targets) {
        if(!mods.includes(mod)) {
            console.error("no mod called " + mod + " with a src/main.ts (have: " + mods.join(", ") + ")");
            Deno.exit(1);
        }
        try {
            await bundleMod(mod, outputOf(mod), null);
        } catch(e) {
            console.error((e as Error).message);
            Deno.exit(1);
        }
        console.log("bundled " + mod + " -> " + outputOf(mod));
    }
}
